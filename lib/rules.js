// Rules from the map: critical ones go to files Claude Code always loads, project ones to files it loads by path,
// on-use ones to an index the PreToolUse hook reads. Stockroom only ever touches files that carry its marker.
import fs from 'node:fs';
import path from 'node:path';
import { claudeDir, readJson, slugger } from './files.js';
import { matchName, mapIndex } from './map.js';
import { normPath } from './pretool.js';

export const MARKER_START = '<!-- generated by Stockroom from ';
const marker = (mapFiles) => `${MARKER_START}${mapFiles.map((f) => path.basename(f)).join(', ')}; edit the map, not this file -->`;
const CRITICAL_MAX = 4096;
const PROJECT_MAX = 3072;

// A project file starts with its paths frontmatter (Claude Code reads it only on line 1), so the marker follows it.
export function isGenerated(text) {
  const lines = String(text).split(/\r?\n/);
  if (lines[0]?.startsWith(MARKER_START)) return true;
  if (lines[0] !== '---') return false;
  const end = lines.indexOf('---', 1);
  return end > 0 && Boolean(lines[end + 1]?.startsWith(MARKER_START));
}

export const keyOf = (t) => (t.kind === 'mcp-server' ? `MCP ${t.name}` : t.name);
const line = (r) => (r.tools.length ? `- ${r.tools.map((t) => `\`${t}\``).join(', ')}: ${r.rule}` : `- ${r.rule}`);

function sizeWarning(label, text, max, rules) {
  const bytes = Buffer.byteLength(text);
  if (bytes <= max) return [];
  const longest = rules.reduce((a, b) => (line(b).length > line(a).length ? b : a));
  return [`${label}: ${bytes} bytes, over ${max}; shorten "${line(longest).slice(2, 60)}…" (${longest.file})`];
}

export function buildRules({ rules, cases, tools, config }, mapFiles = [...new Set(rules.map((r) => r.file))]) {
  const warnings = [];
  const projects = config.projects || {};
  const known = rules.filter((r) => {
    if (r.warning) warnings.push(`${r.file} · ${r.section}: ${r.warning}`);
    if (r.project && !projects[r.project]) { warnings.push(`${r.file} · ${r.section}: unknown project "${r.project}" (add it to "projects")`); return false; }
    if (!r.tools.length && r.level !== 'critical') { warnings.push(`${r.file} · ${r.section}: "${r.rule.slice(0, 50)}": a rule with no tool must be critical`); return false; }
    return true;
  });
  const resolve = (r) => r.tools.flatMap((tok) => {
    const hits = matchName(tok, tools);
    if (!hits.length) warnings.push(`${r.file} · ${r.section}: "${tok}" matches no installed tool`);
    return hits;
  });

  const protectedNames = new Set();
  const index = { rules: {}, paths: {} };
  const byTool = {};
  let criticalCount = 0;
  for (const r of known) {
    const hits = resolve(r);
    for (const t of hits) (byTool[keyOf(t)] ||= []).push(r.level === 'critical' ? `(critical) ${r.rule}` : r.rule);
    if (r.level === 'critical') { criticalCount++; hits.forEach((t) => protectedNames.add(t.name)); continue; }
    for (const t of hits) {
      if (t.kind === 'mcp-server') {
        warnings.push(`${r.file} · ${r.section}: "${r.rule.slice(0, 50)}" for MCP ${t.name}: MCP calls are not hooked, so make it critical or a project rule`);
        continue;
      }
      (index.rules[keyOf(t)] ||= []).push(r.rule);
      if (t.path && /SKILL\.md$/i.test(t.path)) index.paths[normPath(t.path)] = keyOf(t);
    }
  }

  const head = marker(mapFiles);
  const general = known.filter((r) => r.level === 'critical' && !r.project);
  const critical = general.length ? [head, '', '# Critical tool rules', '', ...general.map(line), ''].join('\n') : '';
  warnings.push(...sizeWarning('critical rules', critical, CRITICAL_MAX, general));

  const out = new Map();
  for (const [name, globs] of Object.entries(projects)) {
    const crit = known.filter((r) => r.level === 'critical' && r.project === name);
    const jobs = cases.filter((c) => c.project === name);
    if (!crit.length && !jobs.length) continue;
    const text = ['---', 'paths:', ...globs.map((g) => `  - "${g}"`), '---', head, '', `# ${name}: tool rules`, '',
      ...crit.map(line), '',
      ...(jobs.length ? mapIndex(jobs, { catalogDir: config.catalogDir, max: PROJECT_MAX }).split('\n').slice(1) : [])].join('\n');
    out.set(name, text);
    warnings.push(...sizeWarning(`project "${name}"`, text, PROJECT_MAX, crit.length ? crit : [{ rule: name, tools: [], file: '' }]));
  }
  return { critical, projects: out, index, byTool, protected: protectedNames, criticalCount, warnings };
}

const rulesDir = (home) => path.join(claudeDir(home), 'rules');
const stateDir = (home) => path.join(claudeDir(home), 'stockroom');

export function targets(home, built) {
  const slug = slugger();
  const files = new Map();
  if (built.critical) files.set(path.join(rulesDir(home), 'stockroom-critical.md'), built.critical);
  for (const [name, text] of built.projects) files.set(path.join(rulesDir(home), `stockroom-${slug(name)}.md`), text);
  return files;
}

export function planRules({ home, built }) {
  const files = targets(home, built);
  const applied = readJson(path.join(stateDir(home), 'rules-applied.json'), { files: [] }).files;
  const write = [];
  const conflicts = [];
  for (const [p, text] of files) {
    if (fs.existsSync(p) && !isGenerated(fs.readFileSync(p, 'utf8'))) conflicts.push(p);
    else write.push({ path: p, bytes: Buffer.byteLength(text) });
  }
  const remove = applied.filter((p) => !files.has(p) && fs.existsSync(p));
  return { write, remove, conflicts };
}

function atomicWrite(p, text) {
  const tmp = `${p}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, p);
}

export function writeRules({ home, built, mapFiles }) {
  const plan = planRules({ home, built });
  if (plan.conflicts.length) {
    throw new Error(`not generated by Stockroom, left untouched: ${plan.conflicts.join(', ')}. Rename or delete it, then apply again.`);
  }
  const files = targets(home, built);
  const backup = path.join(stateDir(home), 'backups', `rules-${new Date().toISOString().replace(/[:.]/g, '-')}`);
  fs.mkdirSync(rulesDir(home), { recursive: true });
  // Only files that change: the session-start hook calls this often, and unchanged files need no backup or write.
  const changed = [...files].filter(([p, text]) => !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== text);
  for (const p of [...changed.map(([f]) => f), ...plan.remove].filter((f) => fs.existsSync(f))) {
    fs.mkdirSync(backup, { recursive: true });
    fs.copyFileSync(p, path.join(backup, path.basename(p)));
  }
  for (const p of plan.remove) if (isGenerated(fs.readFileSync(p, 'utf8'))) fs.rmSync(p);
  for (const [p, text] of changed) atomicWrite(p, text);
  fs.mkdirSync(stateDir(home), { recursive: true });
  atomicWrite(path.join(stateDir(home), 'rules-index.json'), JSON.stringify(built.index, null, 2));
  atomicWrite(path.join(stateDir(home), 'rules-applied.json'), JSON.stringify({
    at: new Date().toISOString(), files: [...files.keys()], criticalCount: built.criticalCount, mapFiles,
  }, null, 2));
  return { written: [...files.keys()] };
}

export function removeRules({ home }) {
  const appliedPath = path.join(stateDir(home), 'rules-applied.json');
  const applied = readJson(appliedPath, null);
  if (!applied) return { removed: [] };
  const removed = applied.files.filter((p) => fs.existsSync(p) && isGenerated(fs.readFileSync(p, 'utf8')));
  removed.forEach((p) => fs.rmSync(p));
  for (const f of [appliedPath, path.join(stateDir(home), 'rules-index.json')]) fs.rmSync(f, { force: true });
  return { removed };
}
